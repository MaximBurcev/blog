<?php

namespace App\Console;

use Illuminate\Console\Scheduling\Schedule;
use Illuminate\Foundation\Console\Kernel as ConsoleKernel;

class Kernel extends ConsoleKernel
{
    /**
     * Define the application's command schedule.
     */
    protected function schedule(Schedule $schedule): void
    {
        // Telescope пишет в ту же БД и не чистится сам: без прунинга telescope_entries
        // разрослась до сотен тысяч строк с cookie, CSRF-токенами и биндингами запросов.
        $schedule->command('telescope:prune --hours=48')
            ->daily()
            ->onOneServer()
            ->withoutOverlapping();

        // failed_jobs копится с 2025 года и никем не разбирается.
        $schedule->command('queue:prune-failed --hours=336')
            ->weekly()
            ->onOneServer();

        // queue:prune-batches здесь не стоит намеренно. Батчей в проекте нет
        // (ни одного Bus::batch), таблицы job_batches тоже — и команда падала
        // с «Base table or view not found» каждое воскресенье, когда наступал
        // её weekly-слот (на проде отметилась 16.08.2026). Остальное
        // расписание при этом отрабатывало: schedule:run ловит исключение
        // каждого события отдельно. Заводить таблицу ради чистки того, чего не
        // существует, незачем — правильный порядок обратный: сначала батчи,
        // потом их прунинг.

        // Записи роботов в post_views: их не читает ни одна выборка (аналитика
        // и счётчик под статьёй отсекают их скоупом), а держим мы их только
        // ради возможности пересмотреть вердикт детектора. Через квартал такой
        // разбор уже неинтересен. Живые просмотры команда не трогает.
        $schedule->command('post-views:prune')
            ->weekly()
            ->onOneServer();

        // Журнал поиска: аналитика дальше квартала не смотрит, а текст запроса
        // чувствительнее адреса страницы — держать его вечно значит копить
        // ответственность, которая ежедневно уезжает в бэкап.
        $schedule->command('search-queries:prune')
            ->weekly()
            ->onOneServer();

        // Журнал вызовов модели: за квартал аналитики его никто не читает, а
        // строки продолжают уезжать в ежедневный архив.
        $schedule->command('llm-calls:prune')
            ->weekly()
            ->onOneServer();

        // news:import снят с расписания 24.08.2026 и намеренно сюда не
        // возвращается до починки двух вещей ниже.
        //
        // «Повторные отсеиваются по url ещё до перевода» — так было задумано,
        // но NewsImportService специально НЕ пропускает заглушки
        // (parse_status = failed), чтобы дать второй шанс временному сбою.
        // Потолка у этих попыток нет, а часть ссылок в секции дайджеста —
        // ролики на YouTube, главная php.net и страницы релизов на GitHub, где
        // статьи не существует в принципе. Разбор их не починится никогда.
        //
        // Цена выяснилась, когда заработал журнал llm_calls: 24.08 из 11
        // вызовов модели ВСЕ 11 пришлись на такие заглушки — 55% суточной
        // бесплатной квоты (20 запросов) уходило на страницы, которые не
        // разберутся, и так каждое утро. Это же съедало половину лимита до
        // того, как очередь доходила до живых статей: 21.08 квота кончилась к
        // 18:15 и 18 статей подряд ушли на скрейпер.
        //
        // Обе причины устранены 24.08.2026: StorePostJob переводит заголовок
        // только после успешного извлечения контента (см. extractArticle), а у
        // повторов заглушек появился потолок (releases.news_retry_limit,
        // счётчик posts.parse_attempts). Строку не возвращаем не потому, что
        // блокеры живы, а потому что решение «включать обратно» за владельцем
        // блога: бесплатная квота — 20 запросов в сутки, а статья стоит от
        // двух, и утренний импорт снова будет забирать её часть.
        //
        // Оговорка про цену: лишним запросом оплачивалась не всякая заглушка,
        // а только та, что скачалась и отдала заголовок, но не дала контента
        // по селектору. Сбой скачивания, антибот и отсутствие <h1>/<title> до
        // перевода не доходили и стоили ноль — поэтому вызовов в llm_calls
        // меньше, чем заглушек в posts.
        //
        // Сама команда никуда не делась: `php artisan news:import [url]`.
        // Без аргумента она обходит все заведённые релизы — при ручном запуске
        // это дороже, чем нужно, поэтому удобнее звать с конкретным адресом
        // дайджеста.

        // Просроченные токены сброса пароля не удаляются сами: строки в
        // password_reset_tokens лежали вечно и уезжали в каждый бэкап.
        $schedule->command('auth:clear-resets')
            ->daily()
            ->onOneServer();

        // Бэкапы настроены в config/backup.php, но до сих пор не запускались ничем,
        // кроме ручной задачи Envoy. Только прод: локально это лишний мусор в storage/app.
        $schedule->command('backup:clean')
            ->daily()->at('01:00')
            ->environments(['production'])
            ->onOneServer();

        $schedule->command('backup:run')
            ->daily()->at('01:30')
            ->environments(['production'])
            ->onOneServer()
            ->withoutOverlapping();

        // Проверяет, что свежий бэкап реально существует и укладывается в лимиты
        // config/backup.php: без этого молчаливо сломавшийся backup:run никто не заметит.
        $schedule->command('backup:monitor')
            ->daily()->at('06:00')
            ->environments(['production'])
            ->onOneServer();
    }

    /**
     * Register the commands for the application.
     */
    protected function commands(): void
    {
        $this->load(__DIR__.'/Commands');

        require base_path('routes/console.php');
    }
}
