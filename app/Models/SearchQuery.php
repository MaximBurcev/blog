<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

/**
 * Запрос, набранный читателем в поиске по сайту.
 *
 * Записи намеренно обезличены: кто искал — не хранится вовсе (см. миграцию).
 * Поэтому здесь нет ни связей, ни скоупов по посетителю.
 */
class SearchQuery extends Model
{
    /** Момент запроса фиксирует created_at; обновлять запись нечем. */
    public const UPDATED_AT = null;

    /** Длина колонки query — обрезка обязана совпадать со схемой. */
    public const MAX_LENGTH = 191;

    protected $fillable = [
        'query',
        'results_count',
    ];

    /**
     * Время огрубляется до часа.
     *
     * Отчёт строится по периодам от недели — секундная точность ему не нужна,
     * зато она позволяет сопоставить запрос с записью в post_views, где рядом
     * лежат время просмотра и псевдоним сессии: клик по результату происходит
     * через считанные секунды. Час такое сопоставление не исключает, но делает
     * заметно менее однозначным.
     */
    protected static function booted(): void
    {
        static::creating(function (self $searchQuery) {
            $searchQuery->created_at ??= now()->startOfHour();
        });
    }

    protected $casts = [
        'results_count' => 'integer',
        'created_at' => 'datetime',
    ];

    /**
     * Приводит запрос к виду, в котором его считают: нижний регистр,
     * схлопнутые пробелы, обрезка под длину колонки.
     *
     * Без нормализации «Laravel», «laravel» и «laravel   » превращаются в три
     * отдельные строки отчёта, а весь смысл отчёта — увидеть, что спрашивают
     * чаще всего.
     *
     * Возвращает null, если записывать нечего.
     */
    public static function normalize(string $query): ?string
    {
        // Управляющие символы вырезаем вместе с пробельными: \s их не ловит, а
        // \x00 в отчёте — мусор, который к тому же ломает вывод.
        $normalized = trim((string) preg_replace('/[\s\p{C}]+/u', ' ', $query));

        if ($normalized === '') {
            return null;
        }

        /*
         * Сначала регистр, потом обрезка — порядок важен. mb_strtolower длину
         * не сохраняет: 191 символ «İ» превращается в 382 (U+0130 раскладывается
         * в пару). Обрезав до понижения регистра, мы отдавали бы в VARCHAR(191)
         * строку вдвое длиннее, MySQL в strict-режиме отвечал бы «Data too
         * long», а исключение уносило бы текст запроса в лог — и всё это
         * вызывается одной ссылкой из адресной строки.
         */
        return mb_substr(mb_strtolower($normalized), 0, self::MAX_LENGTH);
    }
}
