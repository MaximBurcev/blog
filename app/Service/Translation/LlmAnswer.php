<?php

namespace App\Service\Translation;

use App\Models\LlmCall;

/**
 * Ответ модели вместе со строкой журнала, которая его зафиксировала.
 *
 * Нужен из-за того, что годность ответа выясняется в два приёма: сетевую
 * сторону знает GeminiTranslator::ask(), а годность разметки — валидатор,
 * который работает уже после возврата. Чтобы перекрасить запись в «отклонён»,
 * вызывающему нужна ссылка на неё.
 *
 * Альтернатива — держать «последний вызов» полем самого переводчика — уже
 * пробовалась в наброске и отброшена: неявное состояние между методами
 * незаметно разъезжается, стоит появиться второму пути вызова.
 *
 * $call пуст, если запись в журнал не удалась. Это не ошибка перевода: журнал
 * расходов не имеет права ронять статью, поэтому вызывающий просто ничего не
 * помечает.
 */
final readonly class LlmAnswer
{
    public function __construct(
        public ?string $text,
        public ?LlmCall $call = null,
    ) {}
}
