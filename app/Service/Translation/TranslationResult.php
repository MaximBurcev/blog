<?php

namespace App\Service\Translation;

/**
 * Результат перевода одного фрагмента.
 *
 * Отдельный объект вместо голой строки нужен ради последнего поля: вызывающий
 * обязан знать, кто именно перевёл текст. История с OCR научила — там неудачный
 * запуск tesseract полгода выглядел как «на картинке нет текста», потому что
 * ошибка и пустой результат были неотличимы. Здесь та же ловушка: молчаливый
 * откат на скрейпер выглядит как успешный перевод, и мы бы годами считали, что
 * работаем через LLM.
 */
final readonly class TranslationResult
{
    /**
     * Имя «движка», которым текст не переведён.
     *
     * Отдельная константа, потому что значение уезжает в posts.translated_by и
     * читается отчётами: строковый литерал в двух местах разъехался бы, и часть
     * непереведённых статей молча перестала бы попадать в выборку.
     */
    public const NO_ENGINE = 'none';

    public function __construct(
        public string $text,
        public string $engine,
        public bool $failed = false,
        /*
         * Перевод состоялся, но не целиком: часть блоков осталась в оригинале.
         * Отдельно от failed, потому что смысл другой — движок сработал, и
         * откатываться на запасной незачем, а вот пометить статью в админке
         * надо. Скрейпер оставляет такие блоки штатно, теряя плейсхолдеры.
         */
        public bool $partial = false,
    ) {}

    public static function success(string $text, string $engine): self
    {
        return new self($text, $engine);
    }

    /**
     * Перевести не удалось ни одним движком — возвращаем исходный текст.
     *
     * Ошибка не бросается: половина непереведённой статьи лучше, чем пятисотка
     * в очереди и потерянный пост, а пометка о неполном переводе доедет до
     * админки через translation_incomplete.
     */
    public static function failure(string $original): self
    {
        return new self($original, self::NO_ENGINE, failed: true);
    }
}
