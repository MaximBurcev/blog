<?php

namespace App\Service\Translation;

use Carbon\CarbonImmutable;

/**
 * Общий на всю цепочку срок перевода одной статьи.
 *
 * Бюджет (translation.gemini.budget_seconds = 240) выведен из
 * StorePostJob::$timeout = 420: перевод обязан оставить джобе время на
 * скачивание страницы, картинки и сохранение. Пока движок был один, это
 * обеспечивалось полем самого движка.
 *
 * С появлением цепочки моделей поле перестало работать сразу двумя способами.
 * Поэкземплярный бюджет умножался на длину цепочки — три модели давали потолок
 * 720 секунд. Попытка поделить 240 на три (24.08.2026) вышла не лучше: 80
 * секунд не хватает статье из трёх кусков, каждый из которых переводится
 * около пятидесяти, и статья 236 стала уходить в таймаут на ровном месте.
 *
 * Правильная единица — статья, а не движок: срок ставит тот, кто взялся за неё
 * первым, а остальные звенья цепочки доедают остаток. Работающая модель может
 * потратить все 240 секунд, а если первая сожгла минуту на исчерпанной квоте,
 * второй достанется столько, сколько осталось.
 *
 * Класс намеренно не знает про очередь и джобы: один процесс воркера в каждый
 * момент разбирает одну статью, а веб-запросы перевод не запускают вовсе.
 */
class TranslationDeadline
{
    private ?CarbonImmutable $expiresAt = null;

    /**
     * Ставит срок, если его ещё нет.
     *
     * Возвращает true тому, кто срок поставил, — только он вправе его снять.
     * Внутренние звенья цепочки получают false и работают в чужом сроке: иначе
     * второй движок обнулил бы счётчик и цепочка снова стала бы длиннее
     * таймаута джобы.
     */
    public function start(float $seconds): bool
    {
        if ($this->expiresAt !== null) {
            return false;
        }

        $this->expiresAt = CarbonImmutable::now()->addSeconds($seconds);

        return true;
    }

    public function stop(): void
    {
        $this->expiresAt = null;
    }

    public function expired(): bool
    {
        return $this->expiresAt !== null && $this->remaining() <= 0;
    }

    /**
     * Сколько секунд осталось. INF, если срок не ставили — перевод заголовка
     * идёт отдельным вызовом, вне статьи, и ограничивать его нечем.
     */
    public function remaining(): float
    {
        if ($this->expiresAt === null) {
            return INF;
        }

        return max(0.0, (float) (CarbonImmutable::now()->diffInMilliseconds($this->expiresAt) / 1000));
    }
}
